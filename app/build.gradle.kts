/**
 * Release signing is configured from environment variables / Gradle properties.
 * Never commit keystores or passwords. When no signing material is present the
 * release APK is built unsigned and the CI workflow reports that explicitly.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

fun secret(name: String, propertyName: String): String? =
    System.getenv(name)?.takeIf { it.isNotBlank() } ?: keystoreProperties.getProperty(propertyName)?.takeIf { it.isNotBlank() }

